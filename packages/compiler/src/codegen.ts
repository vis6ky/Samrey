import { AIRTemplateUnit, AIRCompilationResult } from './air.js';

export function hoistTemplates(templateUnits: AIRTemplateUnit[]): string {
  const hoistedDeclarations = templateUnits.map((u, i) => {
    return `const _tmpl$${i + 1} = /*#__PURE__*/ template(${JSON.stringify(u.staticHtml)});`;
  });

  return hoistedDeclarations.join('\n');
}

export function generateModuleCode(templates: AIRTemplateUnit[], componentBody: string): string {
  const hoisted = hoistTemplates(templates);

  return `// Generated by Aether Compiler AOT
import { template, bindText, bindAttr, on } from '@aether/runtime';

${hoisted}

export default function Render() {
  const root = _tmpl$1();
  ${componentBody}
  return root;
}
`;
}
